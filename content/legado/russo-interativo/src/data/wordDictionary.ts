export function lookupWord(token: string): WordInfo | null {
  const clean = token
    .toLowerCase()
    .replace(/[.,!?;:()«»"—–]/g, '')
    .trim();

  if (!clean) return null;
  return WORD_DICTIONARY[clean] || null;
}
