import assert from 'node:assert/strict';
import {avaliarCompetencia,progressoPercurso,mensagemDeConquista,ETAPAS} from './modelo.mjs';
const skill='de.b1.weil-denn';
const itens=Array.from({length:5},(_,i)=>({skill_id:skill,item_id:`i${i}`,kind:'independent',tentativa:1,ajudas:0,correto:i!==4}));
const rec=n=>({skill_id:skill,item_id:`r${n}`,kind:'review',tentativa:1,ajudas:0,correto:true,intervalo_dias:n});
const transf={skill_id:skill,item_id:'novo-contexto',kind:'transfer',tentativa:1,correto:true,novo_contexto:true,sem_ajuda:true,avaliacao_independente:'aprovado'};
assert.equal(avaliarCompetencia(skill).etapa,ETAPAS.NUNCA);
assert.equal(avaliarCompetencia(skill,[{...itens[0],kind:'guided'}]).etapa,ETAPAS.INICIADA);
assert.equal(avaliarCompetencia(skill,itens).etapa,ETAPAS.PRATICADA);
assert.equal(avaliarCompetencia(skill,[...itens,rec(1),rec(7)]).etapa,ETAPAS.CONSOLIDANDO);
assert.equal(avaliarCompetencia(skill,[...itens,rec(1),rec(7),rec(30),transf]).etapa,ETAPAS.DEMONSTRADA);
assert.equal(avaliarCompetencia(skill,[...itens,itens[0]]).exercicios_validos,5);
assert.equal(avaliarCompetencia(skill,itens.map(e=>({...e,ajudas:1}))).dominio_demonstrado,false);
assert.equal(avaliarCompetencia(skill,[...itens,rec(1),rec(7),rec(30)]).dominio_demonstrado,false);
assert.equal(avaliarCompetencia(skill,[...itens,rec(1),rec(7),transf]).dominio_demonstrado,false);
assert.equal(avaliarCompetencia(skill,[...itens,{...rec(30),correto:false},rec(1),rec(7),transf]).dominio_demonstrado,false);
assert.equal(progressoPercurso(9,24).proporcao,9/24);
assert.equal(progressoPercurso(0,0).proporcao,null);
assert.throws(()=>progressoPercurso(25,24),RangeError);
assert.match(mensagemDeConquista({tipo:'pratica',idioma:'alemão',competencia:'causa',acertos:4,total:5,confirmou:true}),/4 de 5/);
assert.doesNotMatch(mensagemDeConquista({tipo:'pratica',idioma:'alemão',competencia:'causa',acertos:4,total:5,confirmou:false}),/Parabéns/);
console.log('15 verificações de invariantes pedagógicas passaram.');
